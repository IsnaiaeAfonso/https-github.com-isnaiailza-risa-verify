const englishToPortuguese = new Map(Object.entries(translations).map(([portuguese, english]) => [english, portuguese]));
const portugueseToEnglish = new Map(Object.entries(translations));

const LanguageContext = createContext<{ language: Language; setLanguage: (language: Language) => void }>({
  language: "pt",
  setLanguage: () => undefined,
});

function translatedText(value: string, language: Language) {
  const trimmed = value.trim();
  const dictionary = language === "en" ? portugueseToEnglish : englishToPortuguese;
  const exact = dictionary.get(trimmed);
  if (exact) return value.replace(trimmed, exact);

  if (language === "en") {
    const patientCaseMessage = trimmed.match(/^Caso:\s*([A-Za-z0-9_-]+)\.\s*Envie o PDF ao médico selecionado\.$/i);
    if (patientCaseMessage) return `Case: ${patientCaseMessage[1]}. Send the PDF to the selected physician.`;

    const consentCaseMessage = trimmed.match(/^O consentimento é específico para o caso\s+([A-Za-z0-9_-]+)\.$/i);
    if (consentCaseMessage) return `Consent applies specifically to case ${consentCaseMessage[1]}.`;

    const completedDocumentSummary = trimmed.match(/^(\d+)\s+documentos\s*·\s*análise concluída$/i);
    if (completedDocumentSummary) return `${completedDocumentSummary[1]} documents · analysis complete`;

    const countedTab = trimmed.match(/^(Conflitos|Lacunas|Exames)\s*\(\s*(\d+)\s*\)$/i);
    if (countedTab) {
      const noun = countedTab[1].toLowerCase();
      const translatedNoun = noun === "conflitos" ? "Conflicts" : noun === "lacunas" ? "Gaps" : "Tests";
      return `${translatedNoun} (${countedTab[2]})`;
    }

    const countLabel = trimmed.match(/^(\d+)\s+(documentos?|registros?|achados?|conflitos?|revisões?)$/i);
    if (countLabel) {
      const noun = countLabel[2].toLowerCase();
      const translatedNoun: Record<string, [string, string]> = {
        documento: ["document", "documents"],
        documentos: ["document", "documents"],
        registro: ["record", "records"],
        registros: ["record", "records"],
        achado: ["finding", "findings"],
        achados: ["finding", "findings"],
        conflito: ["conflict", "conflicts"],
        conflitos: ["conflict", "conflicts"],
        revisão: ["review", "reviews"],
        revisões: ["review", "reviews"],
      };
      const count = Number(countLabel[1]);
      return `${countLabel[1]} ${translatedNoun[noun][count === 1 ? 0 : 1]}`;
    }
  }

  return value;
}

function translateSubtree(root: Node, language: Language) {
  if (root.nodeType === Node.TEXT_NODE) {
    const currentText = root.nodeValue ?? "";
    const translated = translatedText(currentText, language);
    if (translated !== currentText) root.nodeValue = translated;
    return;
  }

  const ownerDocument = root.ownerDocument ?? (root as Document);
  const walker = ownerDocument.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node: Node | null;
  while ((node = walker.nextNode())) {
    if (!node.nodeValue?.trim()) continue;
    const translated = translatedText(node.nodeValue, language);
    if (translated !== node.nodeValue) node.nodeValue = translated;
  }

  const elements = root instanceof HTMLElement ? [root, ...Array.from(root.querySelectorAll<HTMLElement>("[placeholder], [aria-label], [title]"))] : [];
  for (const element of elements) {
    for (const attribute of ["placeholder", "aria-label", "title"]) {
      const value = element.getAttribute(attribute);
      if (!value) continue;
      const translated = translatedText(value, language);
      if (translated !== value) element.setAttribute(attribute, translated);
    }
  }
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>("pt");

  useEffect(() => {
    const storedLanguage = window.localStorage.getItem(LANGUAGE_KEY);
    if (storedLanguage === "en" || storedLanguage === "pt") setLanguageState(storedLanguage);
  }, []);

  useEffect(() => {
    document.documentElement.lang = language === "en" ? "en" : "pt-BR";
    translateSubtree(document.body, language);

    const observer = new MutationObserver((records) => {
      for (const record of records) {
        if (record.type === "characterData" && record.target instanceof Text) {
          const translated = translatedText(record.target.nodeValue ?? "", language);
          if (translated !== record.target.nodeValue) record.target.nodeValue = translated;
        }
        record.addedNodes.forEach((node) => {
          if (node.nodeType === Node.ELEMENT_NODE || node.nodeType === Node.TEXT_NODE) translateSubtree(node, language);
        });
      }
    });
    observer.observe(document.body, { subtree: true, childList: true, characterData: true });
    return () => observer.disconnect();
  }, [language]);

  function setLanguage(nextLanguage: Language) {
    window.localStorage.setItem(LANGUAGE_KEY, nextLanguage);
    setLanguageState(nextLanguage);
  }

  return <LanguageContext.Provider value={{ language, setLanguage }}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  return useContext(LanguageContext);
}
